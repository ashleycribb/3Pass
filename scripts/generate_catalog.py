"""
Catalog Generator (CONTENTS.md) mirroring OpenAI Math Structure

Compiles corpus contents into thematic Result Families mirroring the layout of `openai/math`,
linking each entry directly to its canonical Google Drive PDF and Karpathy LLM Wiki note.
"""

import os
import sys
import json
import re
import argparse
from datetime import datetime
import yaml

try:
    from scripts.corpus_common import DEFAULT_CONFIG_PATH, load_config
except ImportError:  # run directly as `python scripts/<name>.py`
    from corpus_common import DEFAULT_CONFIG_PATH, load_config


def categorize_paper(title, abstract, theories):
    text = (title + " " + abstract + " " + " ".join(theories)).lower()

    if any(k in text for k in ["symbolic", "neuro-symbolic", "lean", "formal", "logic", "proof", "z3", "theorem"]):
        return "Family 1: Neuro-Symbolic & Formal Reasoning Systems"
    elif any(k in text for k in ["synergy", "agency", "learner", "student", "metacognition", "irt", "collaborative", "co-intelligence"]):
        return "Family 2: Human-AI Synergy, Agency & Cognitive Load"
    elif any(k in text for k in ["agent", "agentic", "tool", "workflow", "coding", "software", "react", "telemetry"]):
        return "Family 3: Agentic Workflows & Autonomous Systems"
    elif any(k in text for k in ["pedagogy", "education", "policy", "governance", "higher education", "classroom", "curriculum"]):
        return "Family 4: Pedagogical Frameworks & Educational Governance"
    else:
        return "Family 5: Benchmark Datasets, Evaluation & Robustness"

def generate_catalog(cfg):
    ledger_path = os.path.join(cfg.get("ledger_dir", "ledger"), "source_ledger.json")
    wiki_dir = cfg.get("wiki_dir", "wiki")
    out_catalog = "CONTENTS.md"

    if not os.path.exists(ledger_path):
        print(f"Error: Ledger file not found at {ledger_path}")
        sys.exit(1)

    with open(ledger_path, "r", encoding="utf-8") as f:
        ledger = json.load(f)

    sources = ledger.get("sources", [])
    families = {
        "Family 1: Neuro-Symbolic & Formal Reasoning Systems": [],
        "Family 2: Human-AI Synergy, Agency & Cognitive Load": [],
        "Family 3: Agentic Workflows & Autonomous Systems": [],
        "Family 4: Pedagogical Frameworks & Educational Governance": [],
        "Family 5: Benchmark Datasets, Evaluation & Robustness": []
    }

    for s in sources:
        fam = categorize_paper(s.get("title", ""), s.get("abstract_excerpt", ""), s.get("theoretical_frameworks", []))
        families[fam].append(s)

    content = f"""# 3Pass Literature Review: Corpus Catalog (CONTENTS.md)

Organized into thematic **Result Families** mirroring the modular repository structure of [`openai/math`](https://github.com/openai/math).  
Each entry provides verifiable provenance tracking back to the active Google Drive research corpus and the local zero-copy S3A binary storage engine.

---

## Catalog Overview
- **Total Corpus Size**: {len(sources)} unique academic documents
- **Active Backend**: S3A Native Hyper-Tile Storage Engine (`ledger/research_corpus.s3a`)
- **Interactive Wiki**: Karpathy LLM Research Wiki (`wiki/`)
- **Last Updated**: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}

---
"""

    for fam_name, papers in families.items():
        content += f"## {fam_name} ({len(papers)} Papers)\n\n"
        content += "| Source ID | Title | Year | Authors | Wiki Note | Pass Status |\n"
        content += "|-----------|-------|------|---------|-----------|-------------|\n"
        
        # Sort papers: researcher-selected / P2 first
        papers.sort(key=lambda p: (p.get("pass_status") != "P2 done", not p.get("researcher_selection")))

        for p in papers[:25]:  # Show top 25 per family
            sid = p["source_id"]
            title_clean = (p.get("title") or "Untitled").replace("|", "-").strip()[:50]
            auth_clean = (p.get("author") or "Unknown").replace("|", "-").strip()[:20]
            wiki_link = f"[`{sid}`](wiki/papers/{sid}.md)" if os.path.exists(os.path.join(wiki_dir, "papers", f"{sid}.md")) else f"`{sid}`"
            content += f"| `{sid}` | {title_clean} | {p.get('year', 'Unknown')} | {auth_clean} | {wiki_link} | `{p.get('pass_status')}` |\n"

        if len(papers) > 25:
            content += f"\n*(Showing top 25 of {len(papers)} records in this family. See `ledger/source_ledger.json` for full catalog)*\n\n"
        else:
            content += "\n"

    content += """---
*Generated by the 3Pass Literature Review Pipeline*
"""

    with open(out_catalog, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"Generated {out_catalog} with {len(sources)} categorized entries.", flush=True)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate CONTENTS.md Catalog")
    parser.add_argument("--config", default=DEFAULT_CONFIG_PATH, help="Path to corpus_config.yaml")
    args = parser.parse_args()

    cfg = load_config(args.config)
    generate_catalog(cfg)
